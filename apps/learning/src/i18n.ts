export type MessageKey = keyof typeof messages;

export function text(language: Language, key: MessageKey, values: Record<string, string | number> = {}): string {
  let result: string = messages[key][language === 'en' ? 0 : 1];
  for (const [name, value] of Object.entries(values)) result = result.replaceAll(`{${name}}`, String(value));
  return result;
}

export function localized(value: LocalizedText | string | undefined, language: Language): string {
  return typeof value === 'string' ? value : value?.[language] ?? '';
}

export function localizedList(value: LocalizedText[] | string[] | undefined, language: Language): string[] {
  return (value ?? []).map((item) => localized(item, language));
}

